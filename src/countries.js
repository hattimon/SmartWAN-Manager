function displayName(code, language) {
  try {
    return new Intl.DisplayNames([language], { type: 'region' }).of(code) || code;
  } catch (_error) {
    return code;
  }
}

export function countryOptions(language = 'en') {
  return ISO_COUNTRY_CODES.map((code) => {
    const localName = displayName(code, language);
    const englishName = displayName(code, 'en');
    const polishName = displayName(code, 'pl');
    const names = [...new Set([localName, polishName, englishName])];
    return {
      code,
      localName,
      englishName,
      polishName,
      search: `${names.join(' ')} ${code}`.toLocaleLowerCase(language),
      label: `${names.join(' / ')} (${code})`,
    };
  }).sort((left, right) => left.localName.localeCompare(right.localName, language));
}

export function findCountry(query, options) {
  const text = String(query || '').trim();
  const codeMatch = text.match(/\(([A-Za-z]{2})\)\s*$/)?.[1]?.toUpperCase()
    || (/^[A-Za-z]{2}$/.test(text) ? text.toUpperCase() : '');
  if (codeMatch) return options.find((option) => option.code === codeMatch) || null;
  const normalized = text.toLocaleLowerCase();
  return options.find((option) => (
    option.localName.toLocaleLowerCase() === normalized
    || option.englishName.toLocaleLowerCase() === normalized
    || option.polishName.toLocaleLowerCase() === normalized
  )) || null;
}
